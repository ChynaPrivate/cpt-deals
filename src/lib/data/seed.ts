/** Join helper used by the local data source. */
export function joinSeed(): SpecialWithRestaurant[] {
  const byId = new Map(RESTAURANTS_SEED.map((r) => [r.id, r]));
  return SPECIALS_SEED.flatMap((special) => {
    const restaurant = byId.get(special.restaurant_id);
    return restaurant ? [{ ...special, restaurant }] : [];
  });
}
